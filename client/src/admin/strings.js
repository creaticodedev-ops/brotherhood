const dictionaries = { fr, en, ar }

/** `a(key, vars)` for admin copy; falls back to French, then to the key itself. */
export const useAdminText = () => {
  const { locale } = useI18n()
  return useCallback(
    (key, vars) => {
      const found = getNested(dictionaries[locale] || fr, key) ?? getNested(fr, key)
      if (typeof found !== 'string') return key
      return vars ? interpolate(found, vars) : found
    },
    [locale],
  )
}
