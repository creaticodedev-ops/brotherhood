export const OPS_COPY = { fr, en, ar }

export const useOpsCopy = () => {
  const { locale } = useI18n()
  return OPS_COPY[locale] || fr
}

/** Maps an API error to one of the shared messages. */
export const errorKey = (error) => {
  if (error?.status === 403) return 'forbidden'
  if (error?.status === 503) return 'offline'
  if (error?.status === 401) return 'session'
  return 'server'
}
